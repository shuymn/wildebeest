-- Kopje Store schema 0019: hashtag names as Mastodon normalizes them. Never edit after release (checksummed).
--
-- A hashtag is its normalized name (src/domain/tag-name.ts), the name status_tags, tag_follows and featured_tags hold.
-- The names were NFKC and lowercase. They are now Mastodon's HashtagNormalizer#normalize: NFKC, String#downcase, then
-- ASCIIFolding#fold (a fixed table of Latin letters with diacritics to ASCII), then the characters a hashtag cannot
-- hold (Tag::HASHTAG_INVALID_CHARS_RE: anything but a character of the Unicode Alphabetic property, a decimal digit,
-- Thai U+0E47 to U+0E4E, _, U+00B7, U+30FB and U+200C) dropped. A stored name is the first two steps applied already,
-- so each is renamed to the last two applied to it, as normalizeTag would name what it was made from. A walk of the
-- name's characters replaces each letter of the folding table (tag_folds: those a lowercase NFKC name can hold; the
-- table's capitals, and the four letters NFKC rewrites, never appear in one) and keeps each character whose code point
-- is in a range a hashtag can hold (tag_characters, written out from Unicode 17's Alphabetic and Decimal_Number; the
-- Store's SQLite has no regular expressions and refuses a GLOB pattern over 50 bytes). Stored names can hold
-- characters that go: a combining mark that is no letter (the dot above that lowercase İ leaves after i, a mark a
-- status's hashtag ended with), a connector other than _, and anything a converted legacy hashtag held.
-- test/migrations.test.ts runs this file on the names of every letter of the table and a sample of other characters
-- and requires normalizeTag's names.
--
-- Two names that become one are merged, as Mastodon has one tag for them:
-- - status_tags keeps one row per status and name. Its public is the status's, the same on every row of the status.
-- - tag_follows keeps the account's earliest follow (the lowest id).
-- - featured_tags keeps the account's earliest featured hashtag (the lowest id, allocated in time order) with its
--   display_name, and deletes the others without a Remove: a Mastodon follower stored the account's featured hashtags
--   under its own normalization, which already made them one, so it holds one featured hashtag for them, and a Remove
--   of any of the names would take that one away (ActivityPub::Activity::Remove#remove_featured_tags finds it by the
--   normalized name). The account's featured hashtags under a renamed name are recounted from its statuses, as
--   featuring one counts (src/domain/featured-tags.ts): its public and unlisted statuses with the hashtag, and the
--   publication time of the newest.
-- A name that becomes empty is no hashtag: its rows are deleted.
--
-- Not recovered: a stored name made from a Σ that ended a word holds ς (String.prototype.toLowerCase's final-sigma
-- rule), where Mastodon's downcase gives σ; the same ς typed as such stays ς in both, so the stored name cannot tell
-- which it was, and it is left as stored. A character whose properties differ between Unicode 17 and the runtime's
-- Unicode is judged by Unicode 17 here and by the runtime's in normalizeTag; status text and received hashtags never
-- stored a character the runtime does not know, so only a converted legacy name could hold one.
--
-- The work grows linearly with the rows read: one pass over each table to find the names with a character other than
-- a-z, 0-9 and _ (status_tags through its name index, so each distinct name once), a walk of each such name's
-- characters (a key lookup in tag_folds and in tag_characters per character; the two tables have a fixed size), then
-- for each renamed name the rows holding it, through the name indexes (status_tags) or one pass (tag_follows,
-- featured_tags), each looking up the account's row of the new name by its unique index. Each featured hashtag
-- recounted walks its account's statuses once, and an account features at most 10.

CREATE TABLE tag_renames (name TEXT NOT NULL PRIMARY KEY, new_name TEXT) WITHOUT ROWID;

INSERT OR IGNORE INTO tag_renames (name) SELECT DISTINCT name FROM status_tags WHERE name GLOB '*[^0-9_a-z]*';

INSERT OR IGNORE INTO tag_renames (name) SELECT name FROM tag_follows WHERE name GLOB '*[^0-9_a-z]*';

INSERT OR IGNORE INTO tag_renames (name) SELECT name FROM featured_tags WHERE name GLOB '*[^0-9_a-z]*';


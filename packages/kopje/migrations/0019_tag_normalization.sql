-- Each character folded (ASCIIFolding#fold), and kept when its code point is in a range of tag_characters.
UPDATE tag_renames SET new_name = (
  WITH RECURSIVE walk(i, c) AS (
    SELECT 1, coalesce((SELECT ascii FROM tag_folds WHERE letter = substr(tag_renames.name, 1, 1)),
      substr(tag_renames.name, 1, 1))
    UNION ALL
    SELECT i + 1, coalesce((SELECT ascii FROM tag_folds WHERE letter = substr(tag_renames.name, i + 1, 1)),
      substr(tag_renames.name, i + 1, 1))
    FROM walk WHERE i < length(tag_renames.name))
  SELECT coalesce(group_concat(c, '' ORDER BY i), '') FROM walk
  WHERE (SELECT last FROM tag_characters WHERE first <= unicode(c) ORDER BY first DESC LIMIT 1) >= unicode(c)
);

